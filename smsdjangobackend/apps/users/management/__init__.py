def _get_all_permissions(basename, app_label):
    """
    Return (codename, name) for all permissions in the given opts.
    """
    permissions = ()
    builtin = _get_builtin_permissions(basename, app_label)
    custom = list(permissions)
    return builtin + custom


def _get_builtin_permissions(basename, app_label):
    """
    Return (codename, name) for all autogenerated permissions.
    By default, this is ('add', 'change', 'delete')
    """
    default_permissions = ('add', 'change', 'delete', 'view')
    perms = []
    for action in default_permissions:
        if app_label == 'screen_name':
            # visible permission
            perms.append((
                'visible_%s_%s' % (basename, action),
                'Can visible %s %s' % (action, basename)
            ))
        elif app_label == 'app_screen_name':
            perms.append((
                'app_%s_%s' % (basename, action),
                'Can visible app %s %s' % (action, basename)
            ))
        elif app_label == 'staff_app_screen_name':
            perms.append((
                'staff_app_%s_%s' % (basename, action),
                'Can visible app %s %s' % (action, basename)
            ))
        else:
            perms.append((
                '%s_%s' % (action, basename),
                'Can %s %s' % (action, basename)
            ))

    return perms

