def custom_create_permissions(app_config, verbosity=2, interactive=True, using=DEFAULT_DB_ALIAS, apps=global_apps,
                              **kwargs):
    if permission_apps['status']:
        return
    try:
        ContentType = apps.get_model('contenttypes', 'ContentType')
        Permission = apps.get_model('auth', 'Permission')
    except LookupError:
        return
    permission_apps['status'] = True
    # This will hold the permissions we're looking for as
    # (content_type, (codename, name))
    searched_perms = []

    custom_ctypes = set()
    for app_label, values in basename.items():
        for app_basenames in values:
            custom_ctype = ContentType.objects.db_manager(using).get(
                model=app_basenames, app_label=app_label)
            custom_ctypes.add(custom_ctype)

            for perm in _get_all_permissions(app_basenames, app_label):
                searched_perms.append((custom_ctype, perm))

    all_perms = set(Permission.objects.using(using).filter(content_type__in=custom_ctypes).values_list(
        'content_type', 'codename'))

    perms = [
        Permission(codename=codename, name=name, content_type=ct)
        for ct, (codename, name) in searched_perms
        if (ct.pk, codename) not in all_perms
    ]
    Permission.objects.using(using).bulk_create(perms)
    if verbosity >= 2:
        for perm in perms:
            print("Adding permission '%s'" % perm)


def get_contenttypes_and_basenames(using, ContentType):
    ContentType.objects.clear_cache()

    content_types = {
        ct.model: ct
        for ct in ContentType.objects.using(using).all()
    }
    app_basenames = {}
    for app_label, value in basename.items():
        for basenames in value:
            app_basenames.update({basenames: app_label})
    return content_types, app_basenames


def custom_create_contenttypes(app_config, verbosity=2, interactive=True, using=DEFAULT_DB_ALIAS, apps=global_apps,
                               **kwargs):
    """
    Create content types for models in the given app.
    """
    if content_type_apps['status']:
        return

    try:
        ContentType = apps.get_model('contenttypes', 'ContentType')
    except LookupError:
        return
    content_type_apps['status'] = True
    content_types, app_basenames = get_contenttypes_and_basenames(
        using, ContentType)

    if not app_basenames:
        return

    cts = [
        ContentType(
            app_label=app_label,
            model=app_basename,
        )
        for (app_basename, app_label) in app_basenames.items()
        if app_basename not in content_types
    ]
    ContentType.objects.using(using).bulk_create(cts)
    if verbosity >= 2:
        for ct in cts:
            print("Adding content type '%s | %s'" % (ct.app_label, ct.model))
